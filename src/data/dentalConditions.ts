export function getToothLabel(tooth: ToothMeta): string {
  const dentitionText = tooth.dentition === 'permanent' ? 'Răng vĩnh viễn' : 'Răng sữa';
  const jawText = tooth.jaw === 'upper' ? 'Hàm trên' : 'Hàm dưới';
  const sideText = tooth.side === 'right' ? 'Phải' : 'Trái';
  return `Răng ${tooth.display} (FDI ${tooth.fdi}) — ${jawText} ${sideText} · ${dentitionText}`;
}

